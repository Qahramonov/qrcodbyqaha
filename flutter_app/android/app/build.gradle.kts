    }

    // Release signing: CI secrets (CH_KEYSTORE file path, CH_KS_PASS, CH_KEY_ALIAS). Without them the APK is signed
    // with the debug key — fine for installing on your own phone, never commit a keystore to the repository.
    val ks = System.getenv("CH_KEYSTORE")
    signingConfigs {
        if (ks != null && file(ks).exists()) {
            create("release") {
                storeFile = file(ks)
                storePassword = System.getenv("CH_KS_PASS")
                keyAlias = System.getenv("CH_KEY_ALIAS")
                keyPassword = System.getenv("CH_KS_PASS")
            }
        }
    }

    buildTypes {
        release {
            signingConfig = signingConfigs.findByName("release") ?: signingConfigs.getByName("debug")
        }
    }
